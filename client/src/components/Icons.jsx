/**
 * Icons — inline SVG vector icon set (stroke style, currentColor).
 *
 * Replaces the emoji glyphs the UI used to sprinkle through headings,
 * buttons, table cells and chat messages. Vector icons scale crisply,
 * inherit the surrounding text color, and render identically on every
 * platform (emoji rendering varies by OS and looks off in a SecOps UI).
 *
 * Usage:  <IconShield size={14} />   — size in px, defaults to 14.
 */
function Svg({ size = 14, children, ...rest }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

